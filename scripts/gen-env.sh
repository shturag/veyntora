#!/usr/bin/env bash
# Writes .env with random values for every secret the local stack uses.
# The compose file has development defaults, so this is optional; use it on any machine
# that other people can reach. An existing .env is never overwritten.
set -euo pipefail

cd "$(dirname "$0")/.."

# Which bundled services compose starts. Leave one out to use your own instead:
# docs/runbooks/external-services.md.
PROFILES="COMPOSE_PROFILES=bundled-keycloak,bundled-langfuse,bundled-grafana"

if [[ -f .env ]]; then
  # Older .env files predate the profiles: add them, so the stack keeps its services.
  if ! grep -q '^COMPOSE_PROFILES=' .env; then
    printf '\n# Added by scripts/gen-env.sh: bundled services compose starts.\n%s\n' "$PROFILES" >> .env
    echo ".env exists; added COMPOSE_PROFILES (bundled Keycloak, Langfuse, Grafana)"
  else
    echo ".env exists; leaving it unchanged"
  fi
  exit 0
fi

rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }
hex() { openssl rand -hex 32; }

pk="pk-lf-$(rand 24)"
sk="sk-lf-$(rand 32)"

umask 077
cat > .env <<EOF
# Generated by scripts/gen-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit.
${PROFILES}
VEY_PG_SUPERUSER_PASSWORD=$(rand)
VEY_DB_PASSWORD=$(rand)
VEY_KEYCLOAK_DB_PASSWORD=$(rand)
VEY_OPENFGA_DB_PASSWORD=$(rand)
VEY_LITELLM_DB_PASSWORD=$(rand)
VEY_LANGFUSE_DB_PASSWORD=$(rand)
VEY_AEGRA_DB_PASSWORD=$(rand)
VEY_VALKEY_PASSWORD=$(rand)
VEY_QDRANT_API_KEY=$(rand)
VEY_S3_ACCESS_KEY=veyntora-$(rand 12)
VEY_S3_SECRET_KEY=$(rand 40)
VEY_LANGFUSE_S3_ACCESS_KEY=langfuse-$(rand 12)
VEY_LANGFUSE_S3_SECRET_KEY=$(rand 40)
VEY_OIDC_CLIENT_SECRET=$(rand)
VEY_KEYCLOAK_SYNC_CLIENT_SECRET=$(rand)
VEY_KEYCLOAK_ADMIN_PASSWORD=$(rand 20)
VEY_DEV_ADMIN_PASSWORD=$(rand 16)
VEY_DEV_EMPLOYEE_PASSWORD=$(rand 16)
VEY_LITELLM_MASTER_KEY=sk-$(rand)
VEY_LITELLM_SALT_KEY=sk-$(rand)
VEY_CLICKHOUSE_PASSWORD=$(rand)
VEY_LANGFUSE_SALT=$(rand)
VEY_LANGFUSE_ENCRYPTION_KEY=$(hex)
VEY_LANGFUSE_NEXTAUTH_SECRET=$(rand)
VEY_LANGFUSE_PUBLIC_KEY=${pk}
VEY_LANGFUSE_SECRET_KEY=${sk}
VEY_LANGFUSE_OTLP_AUTH=$(printf '%s:%s' "$pk" "$sk" | base64 | tr -d '\n')
VEY_LANGFUSE_ADMIN_PASSWORD=$(rand 20)
VEY_GRAFANA_ADMIN_PASSWORD=$(rand 20)
EOF
echo "wrote .env (start from an empty stack: make reset && make up)"
