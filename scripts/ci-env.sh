#!/usr/bin/env bash
# Writes .env for the throwaway services in deploy/compose/ci-infra.yaml (CI, or trying
# Veyntora without your own services; ADR 0033), with random secrets. Their settings are
# passed in the environment, so the Setup page is skipped. With your own services, run
# `make env` and set them up in the browser instead (ADR 0034). An existing .env is never
# overwritten.
#
# Usage: scripts/ci-env.sh [path]   (default: .env)
set -euo pipefail

cd "$(dirname "$0")/.."
out=${1:-.env}

if [[ -f "$out" ]]; then
  echo "$out exists; leaving it unchanged"
  exit 0
fi

rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }

pg=$(rand) db=$(rand) runtime=$(rand) aegra=$(rand) valkey=$(rand)

umask 077
cat > "$out" <<ENV
# Generated by scripts/ci-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) for ci-infra.yaml. Do not commit.
COMPOSE_FILE=deploy/compose/compose.yaml:deploy/compose/ci-infra.yaml

VEY_DATABASE_URL=postgresql+asyncpg://veyntora_runtime:${runtime}@postgres:5432/veyntora
VEY_OWNER_DATABASE_URL=postgresql+asyncpg://veyntora:${db}@postgres:5432/veyntora
VEY_AEGRA_DATABASE_URL=postgresql://aegra:${aegra}@postgres:5432/aegra
VEY_REDIS_URL=redis://:${valkey}@valkey:6379/0
VEY_GRAPHS_REDIS_URL=redis://:${valkey}@valkey:6379/2
VEY_S3_ENDPOINT=http://seaweedfs:8333
VEY_S3_ACCESS_KEY=veyntora-$(rand 12)
VEY_S3_SECRET_KEY=$(rand 40)
VEY_OPENFGA_URL=http://openfga:8080
VEY_OPENBAO_URL=http://openbao:8200
# make test-integration reads the tokens openbao-init wrote from these volumes.
VEY_OPENBAO_API_TOKEN_VOLUME=veyntora_openbao-api-token
VEY_OPENBAO_RUNTIME_TOKEN_VOLUME=veyntora_openbao-runtime-token
VEY_OIDC_ISSUER=http://localhost:8080/realms/veyntora
VEY_OIDC_INTERNAL_BASE=http://keycloak:8080/realms/veyntora
VEY_OIDC_CLIENT_SECRET=$(rand)
VEY_KEYCLOAK_SYNC_CLIENT_SECRET=$(rand)
VEY_INTERNAL_TOKEN_SECRET=$(rand 48)
VEY_CLAMAV_ADDRESS=clamav:3310
VEY_DEV_ADMIN_PASSWORD=$(rand 16)
VEY_DEV_EMPLOYEE_PASSWORD=$(rand 16)
# make test-integration reaches OpenBao from this machine.
VEY_IT_OPENBAO_URL=http://localhost:8200

# The throwaway services' own passwords.
CI_PG_SUPERUSER_PASSWORD=${pg}
CI_DB_PASSWORD=${db}
CI_RUNTIME_DB_PASSWORD=${runtime}
CI_AEGRA_DB_PASSWORD=${aegra}
CI_KEYCLOAK_DB_PASSWORD=$(rand)
CI_OPENFGA_DB_PASSWORD=$(rand)
CI_VALKEY_PASSWORD=${valkey}
CI_KEYCLOAK_ADMIN_PASSWORD=$(rand 20)
ENV
echo "wrote $out (throwaway services: docker compose up -d)"
